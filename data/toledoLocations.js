export function searchToledoLocations(query) {
  if (!query || typeof query !== 'string') return [];
  const q = query.trim().toLowerCase();
  if (q.length < 2) return [];

  // Normalize query: 'brgy' / 'bgy' / 'brgy.'
  const isGenericBrgySearch = /^(brgy\.?|bgy\.?|barangay)$/i.test(q);
  const cleanQ = q.replace(/^brgy\.?\s+/i, '').replace(/^bgy\.?\s+/i, '').replace(/^barangay\s+/i, '').trim();

  // If user simply typed 'brgy' or 'barangay', return the popular/top barangays
  if (isGenericBrgySearch) {
    return TOLEDO_BARANGAYS.map((b) => ({
      id: `local-brgy-${b.name}`,
      formatted: `${b.name}, Toledo City, Cebu`,
      title: b.name,
      subtext: 'Toledo City, Cebu',
      lat: b.lat,
      lon: b.lon,
      isLocal: true,
    }));
  }

  const results = [];

  // 1. Search landmarks
  for (const item of TOLEDO_LANDMARKS) {
    const matchesName = item.name.toLowerCase().includes(q) || item.name.toLowerCase().includes(cleanQ);
    const matchesAlias = item.aliases.some((a) => a.includes(q) || a.includes(cleanQ));
    if (matchesName || matchesAlias) {
      results.push({
        id: `local-lm-${item.name}`,
        formatted: `${item.name}, ${item.subtext}`,
        title: item.name,
        subtext: item.subtext,
        lat: item.lat,
        lon: item.lon,
        category: item.category,
        isLocal: true,
      });
    }
  }

  // 2. Search barangays
  for (const b of TOLEDO_BARANGAYS) {
    const nameLower = b.name.toLowerCase();
    const matchesName = nameLower.includes(q) || nameLower.includes(cleanQ);
    const matchesAlias = b.aliases.some((a) => a.includes(q) || a.includes(cleanQ));
    if (matchesName || matchesAlias) {
      results.push({
        id: `local-brgy-${b.name}`,
        formatted: `${b.name}, Toledo City, Cebu`,
        title: b.name,
        subtext: 'Toledo City, Cebu',
        lat: b.lat,
        lon: b.lon,
        isLocal: true,
      });
    }
  }

  return results;
}
